using System.IO;
using Antlr4.Runtime;
using Antlr4.Runtime.Misc;
using Antlr4.Runtime.Tree;
using Dibbs.Fhir.Liquid.Converter.Exceptions;
using Dibbs.Fhir.Liquid.Converter.Models;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace Dibbs.Fhir.Liquid.Converter.OutputProcessors
{
    /// <summary>
    /// Converts the JSON-like text produced by Liquid templates into a cleaned JSON object.
    /// </summary>
    /// <remarks>
    /// Liquid output can contain extra commas and empty values.
    /// ANTLR generates parsing code from a grammar (a set of syntax rules). Here, json.g4
    /// defines accepted input and AutoGenerated contains the generated C# code.
    /// These components handle parsing and cleanup:
    /// - jsonLexer groups input characters into tokens, such as a brace, string, or number.
    ///   A comma inside a quoted string belongs to that string, not to a separator token.
    /// - jsonParser checks how tokens fit together and builds a parse tree: a temporary
    ///   description of the input's nested objects, arrays, properties, and values.
    /// - JsonListener is the handwritten cleanup code inherited from the Microsoft FHIR Converter.
    ///   ANTLR's tree walker calls its methods as it visits the tree, allowing it
    ///   to rebuild valid JSON without unwanted empty values.
    ///
    /// This class reads only the outer object and its top-level "entry" array itself. Each
    /// other property value, or each element of that array, goes through ANTLR and JsonListener
    /// separately. Newtonsoft.Json then turns that cleaned fragment into the output object model.
    /// For example, {"entry":[{"id":"a"},{"id":"b"}]} produces two separate entry trees
    /// instead of one tree covering the entire bundle. Nested arrays are still parsed by ANTLR.
    ///
    /// This reduces temporary memory: we do not accumulate a whole-bundle token buffer, parse
    /// tree, or cleaned JSON string. It is not streaming from a file or to a response, however:
    /// the complete input text and the growing output JObject/JArray still occupy memory, and
    /// a single very large entry or non-entry property still needs its own complete parse tree.
    /// </remarks>
    internal sealed class BundleJsonParser
    {
        // ANTLR assigns names like T__0 to punctuation literals in json.g4. These aliases
        // make the handwritten parsing code readable. If the grammar changes, check that
        // these names still match the generated parser's punctuation token assignments.
        private const int OpenObject = jsonParser.T__0;
        private const int Comma = jsonParser.T__1;
        private const int CloseObject = jsonParser.T__2;
        private const int Colon = jsonParser.T__3;
        private const int OpenArray = jsonParser.T__4;
        private const int CloseArray = jsonParser.T__5;

        // Both this class and the generated parser advance the same stream of tokens.
        // LA(1) looks at the next token's type without consuming it ("look ahead").
        // LT(1) returns that token itself, including its text and source position.
        // Consume() advances past it. The unbuffered stream can discard consumed tokens
        // when they are no longer needed for ANTLR's lookahead.
        private readonly UnbufferedTokenStream tokens;
        private readonly jsonParser parser;

        /// <summary>
        /// Initializes a new instance of the <see cref="BundleJsonParser"/> class.
        /// Call Parse only once; it consumes the input without rewinding.
        /// </summary>
        /// <param name="input">
        /// The raw input JSON produced by the conversion templates.
        /// </param>
        public BundleJsonParser(string input)
        {
            var lexer = new jsonLexer(new AntlrInputStream(input));

            // ANTLR's default error listeners print diagnostics to the console. Removing
            // them suppresses those messages; it does not itself change lexer error recovery.
            // Removing the lexer error listeners is consistent with the behavior of the previous parser.
            lexer.RemoveErrorListeners();
            tokens = new UnbufferedTokenStream(lexer);
            parser = new jsonParser(tokens)
            {
                // JsonListener needs a parse tree to walk.
                BuildParseTree = true,
                ErrorHandler = new FailFastErrorStrategy(),
            };
            parser.RemoveErrorListeners();
        }

        /// <summary>
        /// Reads the outer JSON object and assembles the cleaned result. This handles syntax
        /// and cleanup only; merging entries and validating FHIR content happen elsewhere.
        /// </summary>
        public JObject Parse()
        {
            try
            {
                var result = new JObject();
                Expect(OpenObject);
                SkipCommas();
                while (tokens.LA(1) != CloseObject)
                {
                    // STRING includes the surrounding quotes and any JSON escapes. Decode
                    // it so an escaped name such as "\u0065ntry" also matches "entry".
                    var propertyName = JsonConvert.DeserializeObject<string>(Expect(jsonParser.STRING).Text);
                    Expect(Colon);

                    // Pass parentDepth: 1 because the value is already inside the bundle's outer object.
                    // ReadValue counts that object toward the maximum allowed nesting depth.
                    var value = propertyName == "entry" && tokens.LA(1) == OpenArray
                        ? ReadEntries()
                        : ReadValue(parentDepth: 1);
                    if (value != null)
                    {
                        // Only values that survive cleanup replace earlier properties with the
                        // same name. Remove then add puts each duplicate at its last surviving position.
                        // For example, {"a":1,"b":2,"a":3} becomes {"b":2,"a":3},
                        // while {"a":1,"a":""} keeps {"a":1} after empty-value cleanup.
                        result.Remove(propertyName);
                        result.Add(propertyName, value);
                    }

                    ReadSeparator(CloseObject);
                }

                // As with json.g4's "json : obj" rule, parsing finishes at the closing brace;
                // this does not add an end-of-input check after that object.
                Expect(CloseObject);
                return result;
            }
            catch (ParseCanceledException)
            {
                // Report ANTLR failures using the same exception type as Expect.
                throw UnexpectedToken();
            }
        }

        /// <summary>
        /// Reads and cleans the top-level entry array one element at a time.
        /// </summary>
        private JToken ReadEntries()
        {
            var entries = new JArray();
            Expect(OpenArray);
            SkipCommas();
            while (tokens.LA(1) != CloseArray)
            {
                // Pass parentDepth: 2 because each entry is inside both the bundle object and its entry array.
                var value = ReadValue(parentDepth: 2);
                if (value != null)
                {
                    entries.Add(value);
                }

                // Check separators even if cleanup removed the element: empty values must
                // not make a missing comma valid (for example, [ {} {} ] remains invalid).
                ReadSeparator(CloseArray);
            }

            Expect(CloseArray);

            // Match JsonListener by removing arrays that are empty after cleanup.
            return entries.Count == 0 ? null : entries;
        }

        /// <summary>
        /// Parses and cleans one complete JSON value, then converts it to a Newtonsoft JToken.
        /// A JToken is an output JSON node (object, array, or scalar), not an ANTLR input token.
        /// Returns C# null if cleanup removes the entire value; a JSON null remains a JToken.
        /// </summary>
        /// <param name="parentDepth">
        /// Number of surrounding objects or arrays to count toward the JSON nesting limit.
        /// </param>
        private JToken ReadValue(int parentDepth)
        {
            // "value" is a rule in json.g4 accepting a string, number, object, array, boolean,
            // or null.
            var tree = parser.value();

            // The walker calls JsonListener's Exit methods after visiting each node's children.
            // They remove empty strings and containers, omit properties whose values were removed,
            // and rebuild JSON with valid commas. JSON null, false, and zero are preserved.
            var listener = new JsonListener();
            ParseTreeWalker.Default.Walk(listener, tree);
            var cleaned = listener.GetResult() as string;
            if (cleaned == null)
            {
                return null;
            }

            using var reader = new JsonTextReader(new StringReader(cleaned))
            {
                // Keep date-looking strings as strings instead of converting them to dates.
                DateParseHandling = DateParseHandling.None,

                // The reader only sees this fragment. Subtract its surrounding objects/arrays
                // to preserve Newtonsoft's default depth limit of 64.
                // This checks the cleaned JSON, after ANTLR has already built the parse tree.
                MaxDepth = 64 - parentDepth,
            };

            using var writer = new JTokenWriter();
            reader.Read();

            // Reads and copies the entire value, including its nested contents
            // WriteToken calls JTokenWriter.WritePropertyName for each nested property
            // WritePropertyName deletes any existing properties with that same name from the current object
            writer.WriteToken(reader);
            return writer.Token;
        }

        /// <summary>
        /// Consumes and returns the next token if its type matches; otherwise throws a parsing error.
        /// </summary>
        private IToken Expect(int type)
        {
            var token = tokens.LT(1);
            if (token.Type != type)
            {
                throw UnexpectedToken();
            }

            tokens.Consume();
            return token;
        }

        /// <summary>
        /// Matches json.g4's separators: a closing brace/bracket or one or more commas.
        /// Leaves the closing token for the caller to consume.
        /// </summary>
        private void ReadSeparator(int closingToken)
        {
            if (tokens.LA(1) == closingToken)
            {
                return;
            }

            // Require a comma before skipping extras so adjacent values such as [1 2] are rejected.
            Expect(Comma);
            SkipCommas();
        }

        /// <summary>
        /// Allows leading commas and extra separator commas, as permitted by json.g4.
        /// </summary>
        private void SkipCommas()
        {
            while (tokens.LA(1) == Comma)
            {
                tokens.Consume();
            }
        }

        /// <summary>
        /// Describes the next unread token's location in the original input. ANTLR counts
        /// lines from one and columns from zero; an unexpected end of input also has a token.
        /// </summary>
        private PostprocessException UnexpectedToken()
        {
            var token = tokens.LT(1);
            return ParsingError($"Unexpected token at line {token.Line}:{token.Column}.");
        }

        /// <summary>
        /// Wraps a syntax error in the converter's standard JSON parsing error code and message.
        /// </summary>
        private static PostprocessException ParsingError(string message)
        {
            return new PostprocessException(
                FhirConverterErrorCode.JsonParsingError,
                string.Format(Resources.JsonParsingError, message));
        }

        /// <summary>
        /// Stops the parser immediately on a syntax error.
        /// </summary>
        private sealed class FailFastErrorStrategy : BailErrorStrategy
        {
            public override void ReportError(Parser recognizer, RecognitionException e)
            {
                // Generated rules call ReportError before Recover. BailErrorStrategy disables
                // recovery, but default reporting can still read earlier tokens that the stream
                // may have discarded. Cancel here so Parse can report the current token's location.
                throw new ParseCanceledException(e);
            }
        }
    }
}
